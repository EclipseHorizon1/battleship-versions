package battleship;

public class Ship {

	
	
	String name;
	int length;
	int hits;
	
	public Ship(){
		name = "";
		length = 0;
		hits = 0;
		
	}
	
	public Ship(String shipName,int shipLength,int shipHits) {
		
		name = shipName; 
		length = shipLength;
		hits = shipHits;
	}
	//setting the parameters for the ships
	}

